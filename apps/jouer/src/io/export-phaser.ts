const DEFAULT_PHASER_VERSION = "4.1.0";
const phaserCdn = (version: string) => `https://cdn.jsdelivr.net/npm/phaser@${version}/dist/phaser.min.js`;

// The Phaser tween property for a model TrackProperty, or null when the property
// can't be tweened faithfully in Phaser (origin*/shape size update display only
// via setOrigin/setSize, so they stay editor-only). Sprite/image display size
// maps to displayWidth/displayHeight, which Phaser tweens correctly. Shared with
// the live multi-engine player so code-gen and live preview animate identically.
export function exportTweenProp(property: TrackProperty, obj: GameObject | undefined): string | null {
  if (property === "x" || property === "y" || property === "scaleX" || property === "scaleY" || property === "angle" || property === "alpha") {
    return property;
  }
  const textured = obj?.kind === "sprite" || obj?.kind === "image";
  // A tiled/sliced sprite/image owns its size via its own width/height (the tiled
  // area / 9-slice size); a plain one via displayWidth/displayHeight (scaling).
  const sized = !!obj && (isTiled(obj) || isSliced(obj));
  if (property === "width") return textured ? (sized ? "width" : "displayWidth") : null;
  if (property === "height") return textured ? (sized ? "height" : "displayHeight") : null;
  return null; // originX, originY, shape width/height — editor-only
}

interface Ctx {
  /** Unique JS identifiers across a scene. */
  used: Set<string>;
}

function ident(base: string, ctx: Ctx): string {
  let s = base.replace(/[^A-Za-z0-9_]/g, "_");
  if (!s || /^[0-9]/.test(s)) s = "o_" + s;
  let name = s;
  let i = 2;
  while (ctx.used.has(name)) name = `${s}${i++}`;
  ctx.used.add(name);
  return name;
}

function pascal(s: string): string {
  return s.replace(/(^|[^A-Za-z0-9])([A-Za-z0-9])/g, (_m, _p, c: string) => c.toUpperCase()).replace(/[^A-Za-z0-9]/g, "") || "Scene";
}

function hex(s: string | null | undefined, fallback = "#000000"): string {
  return (s && /^#?[0-9a-fA-F]{3,8}$/.test(s)) ? (s.startsWith("#") ? s : "#" + s) : fallback;
}
function hex0x(s: string | null | undefined, fallback = 0): string {
  const h = hex(s, "#000000").slice(1);
  const full = h.length === 3 ? h.split("").map((c) => c + c).join("") : h;
  const n = parseInt(full, 16);
  return "0x" + (Number.isFinite(n) ? n : fallback).toString(16);
}
const r2 = (n: number): number => Math.round(n * 1000) / 1000;

// ── public entry points ──────────────────────────────────────
export function exportGameJs(project: Project): string {
  const sceneClassNames = uniqueClassNames(project.scenes);
  const lines: string[] = [];
  lines.push("// ─────────────────────────────────────────────");
  lines.push(`// ${project.name} — generated by Monet Jouer`);
  lines.push("// A self-contained Phaser 4 game. Drop into a project with Phaser 4 loaded.");
  lines.push("// ─────────────────────────────────────────────");
  lines.push("");
  lines.push(transitionHelper());
  lines.push("");

  for (const scene of project.scenes) {
    lines.push(emitScene(project, scene, sceneClassNames));
    lines.push("");
  }

  // The exported game boots the start scene (Unity "Scenes In Build"), falling
  // back to the active scene; Phaser auto-starts scene[0], so it leads the array.
  const boot = bootSceneId(project);
  const order = project.scenes
    .slice()
    .sort((a, b) => (a.id === boot ? -1 : b.id === boot ? 1 : 0))
    .map((s) => sceneClassNames.get(s.id)!);

  lines.push("const config = {");
  lines.push("  type: Phaser.AUTO,");
  lines.push(`  width: ${project.width},`);
  lines.push(`  height: ${project.height},`);
  lines.push(`  backgroundColor: '${hex(project.backgroundColor, "#0c0f16")}',`);
  // Unity Camera transparent background — a see-through canvas (the host page shows
  // through); scenes also skip setBackgroundColor below. Gated so the default stays opaque.
  if (project.transparent === true) lines.push("  transparent: true,");
  lines.push(`  pixelArt: ${isPixelArt(project)},`);
  // Unity Resolution & Presentation → Phaser Scale Manager (how the base
  // resolution fits the window). Matches the live player's scale config.
  const scaleSpec = scaleManagerSpec(project);
  lines.push(`  scale: { mode: Phaser.Scale.${scaleSpec.mode}${scaleSpec.center ? ", autoCenter: Phaser.Scale.CENTER_BOTH" : ""} },`);
  if (project.physics === "arcade") {
    lines.push(`  physics: { default: 'arcade', arcade: { gravity: { y: 0 }, debug: ${project.physicsDebug === true} } },`);
  }
  lines.push(`  scene: [${order.join(", ")}],`);
  lines.push("};");
  lines.push("");
  lines.push("new Phaser.Game(config);");
  lines.push("");
  return lines.join("\n");
}

export function exportStandaloneHtml(project: Project, phaserVersion: string = DEFAULT_PHASER_VERSION): string {
  const js = exportGameJs(project);
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>${escapeHtml(project.name)}</title>
  <style>html,body{margin:0;height:100%;background:${hex(project.backgroundColor, "#0c0f16")};display:grid;place-items:center}</style>
  <script src="${phaserCdn(phaserVersion)}"></script>
</head>
<body>
  <script>
${indent(js, 2)}
  </script>
</body>
</html>
`;
}

// ── scene emission ───────────────────────────────────────────
function uniqueClassNames(scenes: Scene[]): Map<string, string> {
  const used = new Set<string>();
  const map = new Map<string, string>();
  for (const s of scenes) {
    let name = pascal(s.key || s.name);
    let i = 2;
    while (used.has(name)) name = `${pascal(s.key || s.name)}${i++}`;
    used.add(name);
    map.set(s.id, name);
  }
  return map;
}

function emitScene(project: Project, scene: Scene, classNames: Map<string, string>): string {
  const cls = classNames.get(scene.id)!;
  const ctx: Ctx = { used: new Set() };
  const out: string[] = [];
  out.push(`class ${cls} extends Phaser.Scene {`);
  out.push(`  constructor() { super('${scene.key}'); }`);
  out.push("");

  // preload
  const assetsUsed = referencedAssetIds(project, scene);
  out.push("  preload() {");
  if (assetsUsed.size === 0) out.push("    // (no external assets)");
  for (const id of assetsUsed) {
    const a = project.assets.find((x) => x.id === id);
    if (!a) continue;
    if (a.kind === "spritesheet" && a.frameWidth && a.frameHeight) {
      out.push(`    this.load.spritesheet('${a.name}', ${JSON.stringify(a.src)}, { frameWidth: ${a.frameWidth}, frameHeight: ${a.frameHeight}, margin: ${a.margin ?? 0}, spacing: ${a.spacing ?? 0} });`);
    } else if (a.kind === "audio") {
      out.push(`    this.load.audio('${a.name}', ${JSON.stringify(a.src)});`);
    } else {
      out.push(`    this.load.image('${a.name}', ${JSON.stringify(a.src)});`);
    }
  }
  out.push("  }");
  out.push("");

  // create
  out.push("  create() {");
  // Skip the camera background paint when the canvas is transparent (see-through).
  if (project.transparent !== true) out.push(`    this.cameras.main.setBackgroundColor('${hex(scene.backgroundColor, "#1a1d29")}');`);
  // Unity AudioListener.volume / audio master — scales every sound the game plays.
  if (project.masterVolume !== 1) out.push(`    this.sound.volume = ${r2(project.masterVolume)};`);
  if (scene.cameraZoom > 0 && scene.cameraZoom !== 1) out.push(`    this.cameras.main.setZoom(${r2(scene.cameraZoom)});`);
  if (scene.cameraX !== 0 || scene.cameraY !== 0) out.push(`    this.cameras.main.setScroll(${r2(scene.cameraX)}, ${r2(scene.cameraY)});`);
  // Unity Cinemachine Dutch → camera roll; model degrees → Phaser setRotation radians.
  if (scene.cameraRotation !== 0) out.push(`    this.cameras.main.setRotation(${r2((scene.cameraRotation * Math.PI) / 180)});`);
  if (scene.cameraBounds) out.push(`    this.cameras.main.setBounds(0, 0, ${scene.width}, ${scene.height});`);
  if (scene.cameraDeadzoneW > 0 || scene.cameraDeadzoneH > 0) out.push(`    this.cameras.main.setDeadzone(${r2(scene.cameraDeadzoneW)}, ${r2(scene.cameraDeadzoneH)});`);
  if (project.physics === "arcade") {
    out.push(`    this.physics.world.setBounds(0, 0, ${scene.width}, ${scene.height});`);
    if (scene.gravityX) out.push(`    this.physics.world.gravity.x = ${r2(scene.gravityX)};`);
    if (scene.gravityY) out.push(`    this.physics.world.gravity.y = ${r2(scene.gravityY)};`);
  }
  // Per-texture Filter Mode (Unity Texture Import → Filter Mode): override the
  // global pixelArt default for individual textures (loaded above in preload).
  for (const id of assetsUsed) {
    const a = project.assets.find((x) => x.id === id);
    if (!a) continue;
    const fm = textureFilterName(a);
    if (fm) out.push(`    this.textures.get('${a.name}').setFilter(Phaser.Textures.FilterMode.${fm});`);
  }
  out.push("");

  // objects (collect id → js var)
  const vars = new Map<string, string>();
  for (const o of scene.objects) emitObject(project, o, null, vars, ctx, out, "    ");

  // main camera follow (Unity Cinemachine "Follow"); needs the built target var
  if (scene.cameraFollowId && vars.has(scene.cameraFollowId)) {
    const followVar = vars.get(scene.cameraFollowId);
    const lerp = r2(scene.cameraFollowLerp);
    const ox = scene.cameraFollowOffsetX, oy = scene.cameraFollowOffsetY;
    // Cinemachine tracked-object offset lives in startFollow args 5-6, so setting
    // it forces the full 6-arg form (lerp included even when 1). With no offset the
    // existing 1-arg (lerp 1) / 4-arg (lerp != 1) forms are kept unchanged.
    out.push(
      ox !== 0 || oy !== 0
        ? `    this.cameras.main.startFollow(${followVar}, false, ${lerp}, ${lerp}, ${r2(ox)}, ${r2(oy)});`
        : scene.cameraFollowLerp !== 1
          ? `    this.cameras.main.startFollow(${followVar}, false, ${lerp}, ${lerp});`
          : `    this.cameras.main.startFollow(${followVar});`);
  }

  // sprite-sheet animations (guarded so re-entry is safe)
  const anims = project.animations.filter((an) => assetsUsed.has(an.assetId));
  if (anims.length) {
    out.push("");
    out.push("    // sprite-sheet animations");
    for (const an of anims) {
      const asset = project.assets.find((a) => a.id === an.assetId);
      if (!asset) continue;
      out.push(`    if (!this.anims.exists('${an.key}')) this.anims.create({ key: '${an.key}', frames: this.anims.generateFrameNumbers('${asset.name}', { frames: ${JSON.stringify(an.frames)} }), frameRate: ${an.frameRate}, repeat: ${an.repeat}, yoyo: ${an.yoyo} });`);
    }
    // autoplay on sprites that request it
    for (const [id, v] of vars) {
      const o = findObj(scene.objects, id);
      if (o?.kind === "sprite" && !isTiled(o) && !isSliced(o) && o.playAnimation) out.push(`    ${v}.play('${o.playAnimation}');`);
    }
  }

  // timelines → tween chains
  const tlLines = emitTimelines(scene, vars);
  if (tlLines.length) {
    out.push("");
    out.push("    // animation timelines");
    out.push(...tlLines.map((l) => "    " + l));
  }

  // transitions out of this scene
  const trs = project.transitions.filter((t) => t.fromSceneId === scene.id);
  if (trs.length) {
    out.push("");
    out.push("    // scene transitions");
    for (const tr of trs) emitTransition(project, tr, out, "    ");
  }

  out.push("  }");
  out.push("}");
  return out.join("\n");
}

function emitObject(
  project: Project,
  o: GameObject,
  parentVar: string | null,
  vars: Map<string, string>,
  ctx: Ctx,
  out: string[],
  pad: string,
  parentActive = true,
): string {
  const v = ident(o.name || o.kind, ctx);
  const t = o.transform;
  // Unity active state: an object is active-in-hierarchy only if it and every
  // ancestor are active. Inactive ⇒ setActive(false) + hidden + no physics body.
  const selfActive = o.active !== false;
  const effectiveActive = parentActive && selfActive;
  let ctor = "";
  switch (o.kind) {
    case "rectangle":
      ctor = `this.add.rectangle(${r2(t.x)}, ${r2(t.y)}, ${o.width ?? 100}, ${o.height ?? 100}, ${hex0x(o.fill, 0x4ade80)})`;
      break;
    case "ellipse":
      ctor = `this.add.ellipse(${r2(t.x)}, ${r2(t.y)}, ${o.width ?? 100}, ${o.height ?? 100}, ${hex0x(o.fill, 0x60a5fa)})`;
      break;
    case "triangle": {
      const w = o.width ?? 100, h = o.height ?? 100;
      ctor = `this.add.triangle(${r2(t.x)}, ${r2(t.y)}, 0, ${h}, ${w / 2}, 0, ${w}, ${h}, ${hex0x(o.fill, 0xf472b6)})`;
      break;
    }
    case "hexagon": {
      const pts = JSON.stringify(hexagonPoints(o.width ?? 100, o.height ?? 100).map(r2));
      ctor = `this.add.polygon(${r2(t.x)}, ${r2(t.y)}, ${pts}, ${hex0x(o.fill, 0xfbbf24)})`;
      break;
    }
    case "hexagonFlat": {
      const pts = JSON.stringify(hexagonFlatPoints(o.width ?? 100, o.height ?? 100).map(r2));
      ctor = `this.add.polygon(${r2(t.x)}, ${r2(t.y)}, ${pts}, ${hex0x(o.fill, 0xfbbf24)})`;
      break;
    }
    case "diamond": {
      const pts = JSON.stringify(diamondPoints(o.width ?? 100, o.height ?? 100).map(r2));
      ctor = `this.add.polygon(${r2(t.x)}, ${r2(t.y)}, ${pts}, ${hex0x(o.fill, 0xa78bfa)})`;
      break;
    }
    case "capsule": {
      const pts = JSON.stringify(capsulePoints(o.width ?? 100, o.height ?? 100).map(r2));
      ctor = `this.add.polygon(${r2(t.x)}, ${r2(t.y)}, ${pts}, ${hex0x(o.fill, 0x2dd4bf)})`;
      break;
    }
    case "text":
      ctor = `this.add.text(${r2(t.x)}, ${r2(t.y)}, ${JSON.stringify(o.text ?? "")}, ${JSON.stringify(textStyle(o))})`;
      break;
    case "image":
    case "sprite": {
      const an = `'${assetName(project, o.assetId)}'`;
      const frameArg = o.kind === "sprite" && o.frame != null ? `, ${JSON.stringify(o.frame)}` : "";
      if (isTiled(o)) {
        const d = drawSize(o);
        ctor = `this.add.tileSprite(${r2(t.x)}, ${r2(t.y)}, ${d.width}, ${d.height}, ${an}${frameArg})`;
      } else if (isSliced(o)) {
        const d = drawSize(o), b = sliceBorders(o);
        const frame = o.kind === "sprite" && o.frame != null ? JSON.stringify(o.frame) : "undefined";
        ctor = `this.add.nineslice(${r2(t.x)}, ${r2(t.y)}, ${an}, ${frame}, ${d.width}, ${d.height}, ${b.left}, ${b.right}, ${b.top}, ${b.bottom})`;
      } else {
        ctor = `this.add.${o.kind}(${r2(t.x)}, ${r2(t.y)}, ${an}${frameArg})`;
      }
      break;
    }
    case "container":
      ctor = `this.add.container(${r2(t.x)}, ${r2(t.y)})`;
      break;
  }
  out.push(`${pad}const ${v} = ${ctor};`);
  vars.set(o.id, v);

  // common setters
  const setters: string[] = [];
  if (o.kind !== "container") setters.push(`setOrigin(${r2(t.originX)}, ${r2(t.originY)})`);
  if (t.scaleX !== 1 || t.scaleY !== 1) setters.push(`setScale(${r2(t.scaleX)}, ${r2(t.scaleY)})`);
  if (t.angle) setters.push(`setAngle(${r2(t.angle)})`);
  if (t.alpha !== 1) setters.push(`setAlpha(${r2(t.alpha)})`);
  if (!parentVar) setters.push(`setDepth(${effectiveDepth(o, sortingLayers(project))})`);
  // Hidden when its own `visible` is off OR it is inactive in hierarchy (so a
  // cascade-disabled child is explicitly hidden, like the player does — not left
  // relying on Phaser's container-visibility propagation). setActive(false) is
  // emitted only for an object whose OWN active is off (Unity's activeSelf).
  if (!o.visible || !effectiveActive) setters.push(`setVisible(false)`);
  if (!selfActive) setters.push(`setActive(false)`);
  if (o.tag && o.tag !== DEFAULT_TAG) setters.push(`setData('tag', ${JSON.stringify(o.tag)})`);
  if ((o.kind === "sprite" || o.kind === "image") && !isSliced(o) && o.tint) setters.push(`setTint(${hex0x(o.tint, 0xffffff)})`);
  if ((o.kind === "rectangle" || o.kind === "ellipse" || o.kind === "triangle" || o.kind === "hexagon" || o.kind === "hexagonFlat" || o.kind === "diamond" || o.kind === "capsule") && (o.strokeWidth ?? 0) > 0) {
    setters.push(`setStrokeStyle(${o.strokeWidth}, ${hex0x(o.stroke, 0x000000)})`);
  }
  if ((o.kind === "sprite" || o.kind === "image") && !isTiled(o) && !isSliced(o) && o.width && o.height) setters.push(`setDisplaySize(${o.width}, ${o.height})`);
  if ((o.kind === "sprite" || o.kind === "image") && !isSliced(o) && o.flipX) setters.push(`setFlipX(true)`);
  if ((o.kind === "sprite" || o.kind === "image") && !isSliced(o) && o.flipY) setters.push(`setFlipY(true)`);
  if (o.kind !== "container" && !isNormalBlend(o.blendMode)) setters.push(`setBlendMode('${phaserBlendName(o.blendMode)}')`);
  if (setters.length) out.push(`${pad}${v}.${setters.join(".")};`);

  if (parentVar) out.push(`${pad}${parentVar}.add(${v});`);

  // physics body (skipped for inactive-in-hierarchy objects — Unity disables
  // components on inactive GameObjects)
  if (project.physics === "arcade" && o.body && o.kind !== "container" && effectiveActive) {
    out.push(`${pad}this.physics.add.existing(${v}${o.body.bodyType === "static" ? ", true" : ""});`);
    const b = o.body;
    const body = `${v}.body`;
    if (b.shape === "circle") {
      // Unity CircleCollider2D.radius overrides the auto-fit; Collider2D Offset
      // folds into the circle's centring offset.
      const c = colliderCircle(o, b.radius);
      out.push(`${pad}${body}.setCircle(${r2(c.radius)}, ${r2(c.offsetX + (b.offsetX ?? 0))}, ${r2(c.offsetY + (b.offsetY ?? 0))});`);
    } else {
      // Unity BoxCollider2D.size — explicit hitbox dims override the auto-fit.
      // setSize re-centres the offset, so it must precede setOffset.
      if ((b.sizeW ?? 0) > 0 && (b.sizeH ?? 0) > 0) out.push(`${pad}${body}.setSize(${r2(b.sizeW!)}, ${r2(b.sizeH!)});`);
      if (b.offsetX || b.offsetY) out.push(`${pad}${body}.setOffset(${r2(b.offsetX ?? 0)}, ${r2(b.offsetY ?? 0)});`);
    }
    if (o.body.bodyType === "dynamic") {
      if (b.velocityX || b.velocityY) out.push(`${pad}${body}.setVelocity(${r2(b.velocityX)}, ${r2(b.velocityY)});`);
      // Unity ConstantForce2D → continuous acceleration (dynamic bodies only).
      if (b.accelerationX || b.accelerationY) out.push(`${pad}${body}.setAcceleration(${r2(b.accelerationX ?? 0)}, ${r2(b.accelerationY ?? 0)});`);
      if (b.gravityY) out.push(`${pad}${body}.setGravityY(${r2(b.gravityY)});`);
      if (b.bounceX || b.bounceY) out.push(`${pad}${body}.setBounce(${r2(b.bounceX)}, ${r2(b.bounceY)});`);
      if (b.collideWorldBounds) out.push(`${pad}${body}.setCollideWorldBounds(true);`);
      if (!b.allowGravity) out.push(`${pad}${body}.setAllowGravity(false);`);
      if (b.immovable) out.push(`${pad}${body}.setImmovable(true);`);
      if ((b.mass ?? 1) !== 1 && (b.mass ?? 1) > 0) out.push(`${pad}${body}.setMass(${r2(b.mass!)});`);
      if ((b.drag ?? 0) > 0) out.push(`${pad}${body}.setDrag(${r2(b.drag!)}, ${r2(b.drag!)});`);
      if (b.angularVelocity) out.push(`${pad}${body}.setAngularVelocity(${r2(b.angularVelocity)});`);
      // Unity ConstantForce2D torque → continuous angular acceleration (dynamic only).
      if (b.angularAcceleration) out.push(`${pad}${body}.setAngularAcceleration(${r2(b.angularAcceleration)});`);
      if ((b.angularDrag ?? 0) > 0) out.push(`${pad}${body}.setAngularDrag(${r2(b.angularDrag!)});`);
      if (b.freezeRotation) out.push(`${pad}${body}.setAllowRotation(false);`);
    } else if (o.body.bodyType === "kinematic") {
      // Unity Kinematic: a dynamic arcade body that ignores gravity and isn't
      // pushed (immovable), but still moves by its own velocity. mass/drag are
      // intentionally omitted (a kinematic body ignores forces); bounce +
      // collideWorldBounds are kept but are inert while immovable (an immovable
      // body is excluded from collision separation).
      out.push(`${pad}${body}.setImmovable(true);`);
      out.push(`${pad}${body}.setAllowGravity(false);`);
      if (b.velocityX || b.velocityY) out.push(`${pad}${body}.setVelocity(${r2(b.velocityX)}, ${r2(b.velocityY)});`);
      if (b.angularVelocity) out.push(`${pad}${body}.setAngularVelocity(${r2(b.angularVelocity)});`);
      if (b.bounceX || b.bounceY) out.push(`${pad}${body}.setBounce(${r2(b.bounceX)}, ${r2(b.bounceY)});`);
      if (b.collideWorldBounds) out.push(`${pad}${body}.setCollideWorldBounds(true);`);
      if ((b.angularDrag ?? 0) > 0) out.push(`${pad}${body}.setAngularDrag(${r2(b.angularDrag!)});`);
      if (b.freezeRotation) out.push(`${pad}${body}.setAllowRotation(false);`);
    }
  }

  // audio source (Unity AudioSource "Play On Awake") — skipped for inactive-in-
  // hierarchy objects, like physics bodies above, and for a dangling clip (a
  // deleted asset) so the generated game never plays an unloaded key.
  const clip = o.audio && playsOnAwake(o.audio) && effectiveActive
    ? project.assets.find((a) => a.id === o.audio!.assetId)
    : undefined;
  if (clip) {
    const cfg = soundConfig(o.audio!);
    const cfgStr = Object.keys(cfg).length ? `, ${JSON.stringify(cfg)}` : "";
    out.push(`${pad}this.sound.play('${clip.name}'${cfgStr});`);
  }

  // recurse children
  if (o.kind === "container" && o.children) {
    for (const c of o.children) emitObject(project, c, v, vars, ctx, out, pad, effectiveActive);
  }
  return v;
}

function emitTimelines(scene: Scene, vars: Map<string, string>): string[] {
  const out: string[] = [];
  let declaredMap = false;
  for (const tl of scene.timelines) {
    const ext = timelineExtent(tl);
    const chains: string[][] = [];
    const skipped: AnimTrack[] = [];
    for (const tr of activeTracks(tl)) {
      if (tr.keyframes.length === 0 || !vars.has(tr.targetId)) continue;
      const obj = findObj(scene.objects, tr.targetId);
      const prop = exportTweenProp(tr.property, obj);
      if (prop) chains.push(emitTrackChain(tl, tr, vars.get(tr.targetId)!, prop, ext));
      else skipped.push(tr);
    }
    if (chains.length === 0 && skipped.length === 0) continue;
    out.push(`// timeline: ${tl.name}${tl.loop ? " (loop)" : ""}`);
    if (!tl.autoplay) out.push(`// paused — start it with: this.mjTimelines[${JSON.stringify(tl.name)}].forEach((t) => t.play());`);
    if (!declaredMap) { out.push("this.mjTimelines = this.mjTimelines || {};"); declaredMap = true; }
    out.push(`this.mjTimelines[${JSON.stringify(tl.name)}] = this.mjTimelines[${JSON.stringify(tl.name)}] || [];`);
    for (const c of chains) out.push(...c);
    if (skipped.length) out.push(`// note: ${skipped.length} origin/size track(s) animate in the editor only — Phaser can't tween origin/shape-size faithfully.`);
  }
  return out;
}

function emitTrackChain(tl: Timeline, track: AnimTrack, v: string, prop: string, ext: number): string[] {
  const kfs = track.keyframes;
  const out: string[] = [];
  // initial value
  out.push(`${v}.${prop} = ${r2(kfs[0].value)};`);
  if (kfs.length < 2) return out;

  const tweens: string[] = [];
  for (let i = 0; i < kfs.length - 1; i++) {
    const a = kfs[i], b = kfs[i + 1];
    const dur = Math.max(0, Math.round((b.time - a.time) * 1000));
    const easeExpr = a.ease === "hold" ? "function (t) { return t < 1 ? 0 : 1; }" : `'${phaserEase(a.ease)}'`;
    const delay = i === 0 && a.time > 0 ? `, delay: ${Math.round(a.time * 1000)}` : "";
    tweens.push(`    { ${prop}: ${r2(b.value)}, duration: ${dur}, ease: ${easeExpr}${delay} },`);
  }
  // For a looping timeline, pad each chain to the shared timeline extent so all
  // tracks restart in phase (a track that ends early holds its last value),
  // matching the editor's single master playhead.
  if (tl.loop) {
    const last = kfs[kfs.length - 1];
    const tail = Math.round((ext - last.time) * 1000);
    if (tail > 0) tweens.push(`    { ${prop}: ${r2(last.value)}, duration: ${tail}, ease: 'Linear' },`);
  }
  // Unity Animator speed: scale the played chain's timeScale. The chain builder
  // ignores a `timeScale` config key, so set it on the instance via Object.assign.
  out.push(`this.mjTimelines[${JSON.stringify(tl.name)}].push(${tl.speed !== 1 ? "Object.assign(" : ""}this.tweens.chain({`);
  out.push(`  targets: ${v},`);
  if (tl.loop) out.push(`  loop: -1,`);
  if (!tl.autoplay) out.push(`  paused: true,`);
  out.push(`  tweens: [`);
  for (const t of tweens) out.push(t);
  out.push(`  ],`);
  out.push(tl.speed !== 1 ? `}), { timeScale: ${r2(tl.speed)} }));` : `}));`);
  return out;
}

function emitTransition(project: Project, tr: Transition, out: string[], pad: string): void {
  const target = project.scenes.find((s) => s.id === tr.toSceneId);
  if (!target) return;
  const key = target.key;
  const opts = `{ kind: '${tr.kind}', duration: ${tr.duration}, direction: '${tr.direction}' }`;
  const call = `mjTransition(this, '${key}', ${opts})`;
  switch (tr.trigger) {
    case "pointerdown":
      out.push(`${pad}this.input.once('pointerdown', () => ${call});`);
      break;
    case "key":
      out.push(`${pad}this.input.keyboard.once('keydown-${(tr.triggerKey || "SPACE").toUpperCase()}', () => ${call});`);
      break;
    case "timer":
      out.push(`${pad}this.time.delayedCall(${tr.delay ?? 1000}, () => ${call});`);
      break;
    case "manual":
      out.push(`${pad}// manual transition — call this.go_${key}() to run it`);
      out.push(`${pad}this.go_${key} = () => ${call};`);
      break;
  }
}

function transitionHelper(): string {
  return `// Shared transition helper used by the generated scenes.
function mjTransition(scene, targetKey, opts) {
  const cam = scene.cameras.main;
  if (opts.kind === 'slide' || opts.kind === 'wipe') {
    scene.scene.transition({
      target: targetKey,
      duration: opts.duration,
      moveBelow: true,
      onUpdate: (t) => {
        const w = scene.scale.width, h = scene.scale.height;
        const dx = (opts.direction === 'left' ? -1 : opts.direction === 'right' ? 1 : 0) * w * t;
        const dy = (opts.direction === 'up' ? -1 : opts.direction === 'down' ? 1 : 0) * h * t;
        cam.setScroll(dx, dy);
      },
    });
    return;
  }
  if (opts.kind === 'zoom') {
    scene.tweens.add({ targets: cam, zoom: 2, alpha: 0, duration: opts.duration, onComplete: () => scene.scene.start(targetKey) });
    return;
  }
  // fade / none
  cam.fadeOut(opts.kind === 'none' ? 0 : opts.duration);
  cam.once('camerafadeoutcomplete', () => scene.scene.start(targetKey));
}`;
}

// ── small helpers ────────────────────────────────────────────
function referencedAssetIds(project: Project, scene: Scene): Set<string> {
  const ids = new Set<string>();
  const walk = (list: GameObject[]) => {
    for (const o of list) {
      if ((o.kind === "sprite" || o.kind === "image") && o.assetId) ids.add(o.assetId);
      if (o.audio?.assetId) ids.add(o.audio.assetId);
      if (o.children) walk(o.children);
    }
  };
  walk(scene.objects);
  // include assets used by any animation referenced by a playing sprite
  for (const an of project.animations) {
    for (const o of flatten(scene.objects)) {
      if (o.kind === "sprite" && o.playAnimation === an.key) ids.add(an.assetId);
    }
  }
  return ids;
}

function flatten(list: GameObject[]): GameObject[] {
  const out: GameObject[] = [];
  const walk = (l: GameObject[]) => l.forEach((o) => { out.push(o); if (o.children) walk(o.children); });
  walk(list);
  return out;
}

function findObj(list: GameObject[], id: string): GameObject | undefined {
  return flatten(list).find((o) => o.id === id);
}

function assetName(project: Project, assetId: string | null | undefined): string {
  return project.assets.find((a) => a.id === assetId)?.name ?? "__missing__";
}

function textStyle(o: GameObject): Record<string, unknown> {
  const s = o.style;
  const style: Record<string, unknown> = {
    fontFamily: s?.fontFamily ?? "Arial",
    fontSize: `${s?.fontSize ?? 32}px`,
    color: s?.color ?? "#ffffff",
    fontStyle: s?.fontStyle ?? "normal",
    align: s?.align ?? "left",
    stroke: s?.stroke ?? "#000000",
    strokeThickness: s?.strokeThickness ?? 0,
    lineSpacing: s?.lineSpacing ?? 0,
    letterSpacing: s?.letterSpacing ?? 0,
  };
  const wrap = s?.wrapWidth ?? 0;
  if (wrap > 0) style.wordWrap = { width: wrap, useAdvancedWrap: true };
  const shadow = textShadowConfig(s);
  if (shadow) style.shadow = shadow;
  return style;
}

function indent(text: string, spaces: number): string {
  const p = " ".repeat(spaces);
  return text.split("\n").map((l) => (l ? p + l : l)).join("\n");
}

function escapeHtml(s: string): string {
  return s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]!));
}
